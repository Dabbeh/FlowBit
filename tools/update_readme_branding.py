"""Apply the Flowbit rebrand to README.md: title, tagline, icon description,
palette table and the NetValve->Flowbit migration note.

Kept as a script rather than a series of hand edits because the README contains
non-ASCII characters (dashes, arrows, >=) that a PowerShell round-trip would
mangle - the exact failure mode that corrupted the sources earlier.

Run:  python update_readme_branding.py
"""

import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
README = os.path.normpath(os.path.join(HERE, "..", "README.md"))

text = io.open(README, encoding="utf-8").read()

# --- replace the whole Brand section ---------------------------------------
start = text.index("## Brand")
end = text.index("## Interface design")
brand = """## Brand

**Flowbit** - *Control Your Connection.*
System-wide bandwidth control for Windows.

The mark is the **Flowing F**, generated by `tools/make_icon.py` into
`src/flowbit.ico` (9 sizes, 16\u2013256 px, so the taskbar, tray, Start Menu and
Alt-Tab each get a native rendering rather than a scaled one):

- Rounded dark navy plate (`#0F172A`), flat with subtle depth.
- An abstract **F** built from two smooth, flowing horizontal strokes plus a
  full-height stem, all with rounded caps.
- Filled with a cyan \u2192 electric-blue gradient (`#06B6D4` \u2192 `#3B82F6`, with a
  brighter `#22D3EE` highlight at the top).
- No text, and deliberately not a Wi-Fi arc, globe or speedometer glyph.

Geometry is tuned for legibility at 16 px: below 24 px the mark uses a
simplified variant (no inner highlight, slightly longer middle bar), because a
faithful miniature of the full artwork turns to mush at tray size.

Regenerate with `python tools/make_icon.py`, which also writes
`docs/flowbit-256.png`, `docs/flowbit-512.png`, `docs/flowbit-lockup.png` (mark +
wordmark: white "Flow" + cyan "bit") and `docs/flowbit.svg`.

### Palette

| Role | Colour | Notes |
| --- | --- | --- |
| Brand navy (panels, icon plate) | `#0F172A` | replaces the old charcoal |
| Primary accent (brand blue) | `#3B82F6` | gradient end, focus rings |
| Secondary accent (brand cyan) | `#06B6D4` | gradient start, download trace |
| Primary text | `#FFFFFF` | |
| Secondary text | `#94A3B8` | |

Functional colours were **deliberately not rebranded**, because their meaning
would be lost:

| Role | Colour | Rationale |
| --- | --- | --- |
| Upload / outgoing | `#FF8C00` orange | recolouring it blue would make upload indistinguishable from download |
| Healthy / enabled | `#2ECC71` green | |
| Warning / near quota | `#F1C40F` amber | |
| Error / destructive | `#E74C3C` red | |

### Rebranding note (NetValve \u2192 Flowbit)

The config directory moved with the rename, and that is the one part of a
rebrand that can destroy user data. `SettingsStore` therefore:

1. prefers the new `Flowbit` directory, but
2. **keeps reading the legacy `NetValve` directory** while it is the only one
   holding data, and
3. **copies** (never moves) `settings.json` and every `usage-YYYY-MM.json`
   forward on first run, skipping any file that is not newer than its target.

The originals are left in place so a downgrade still finds them. An existing
install keeps its settings, its 30-day usage history and its quota cycle; the
About card says so explicitly when the legacy directory is in use. Covered by
`test_migration`.

"""
text = text[:start] + brand + text[end:]

# --- refresh the tagline line and the strapline ----------------------------
text = text.replace(
    "A Windows desktop app that caps **system-wide** internet speed \u2014 not just one\n"
    "app's traffic \u2014 with **hourly schedules**.",
    "Flowbit caps **system-wide** internet speed \u2014 not just one app's traffic \u2014\n"
    "with **hourly schedules**.",
)

# --- test counts ------------------------------------------------------------
text = text.replace("tools\\run_tests.ps1     # 142 checks", "tools\\run_tests.ps1     # 155 checks")
text = text.replace("tools\\run_ui_test.ps1   # 48 checks", "tools\\run_ui_test.ps1   # 62 checks")
text = text.replace(
    "Three test suites plus a headless UI test, none of which need Administrator\nrights or touch the network:",
    "Seven test suites plus a headless UI test \u2014 **217 checks** \u2014 none of which need\n"
    "Administrator rights or touch the network:",
)

# --- migration row in the suite table -------------------------------------
marker = "| `test_interfaces` (38) |"
migration_row = (
    "| `test_migration` (13) | The rebrand's data path: legacy NetValve settings and monthly "
    "usage history copy forward byte-for-byte, originals survive for downgrades, newer files "
    "are never clobbered, and corrupt legacy data falls back to defaults |\n"
)
if "| `test_migration`" not in text:
    text = text.replace(marker, migration_row + marker)

io.open(README, "w", encoding="utf-8", newline="").write(text)
print("README branding updated")
print("lines:", len(text.splitlines()))
